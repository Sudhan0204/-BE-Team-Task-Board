/**
 * Standard Application Error class for controlled operational HTTP errors.
 */
export class ApiError extends Error {
  /**
   * @param {number} statusCode - HTTP status code (4xx, 5xx)
   * @param {string} message - Human-readable error message
   * @param {Array<Object>} [errors=[]] - Array of specific validation or field errors
   * @param {boolean} [isOperational=true] - Marks expected operational errors vs unhandled bugs
   */
  constructor(statusCode, message, errors = [], isOperational = true) {
    super(message);
    this.statusCode = statusCode;
    this.isOperational = isOperational;
    this.errors = errors;
    Error.captureStackTrace(this, this.constructor);
  }

  static badRequest(message = 'Bad Request', errors = []) {
    return new ApiError(400, message, errors);
  }

  static unauthorized(message = 'Authentication required') {
    return new ApiError(401, message);
  }

  static forbidden(message = 'You do not have permission to perform this action') {
    return new ApiError(403, message);
  }

  static notFound(message = 'Requested resource not found') {
    return new ApiError(404, message);
  }

  static conflict(message = 'Resource conflict or duplicate entry', errors = []) {
    return new ApiError(409, message, errors);
  }

  static unprocessable(message = 'Validation failed', errors = []) {
    return new ApiError(422, message, errors);
  }

  static tooManyRequests(message = 'Too many requests. Please try again later.') {
    return new ApiError(429, message);
  }

  static internal(message = 'Internal server error') {
    return new ApiError(500, message, [], false);
  }
}

export default ApiError;
